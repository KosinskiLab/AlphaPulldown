#!/usr/bin/env python3
"""Collect Gate 0: $BENCH/gate0/runs/*/*/cells.jsonl -> $BENCH/gate0/GATE0.md + gate0_cells.tsv.

Speed-ups are stock_ms / arm_ms (> 1 = the arm is faster than our fork's module). The projection multiplies each layer's saving by
how often one AF3 prediction (one seed: 10 recycles + 1, 5 diffusion samples, 4 template slots) calls it:
  C=128: trunk 48 layers x 11 + MSA stack 4 x 11 + confidence head 4 x 5 samples = 592 calls of each variant
  C=64 : template stack 2 layers x 4 templates x 11 = 88 calls of each variant
(each layer has trimul_out + trimul_in and att_start + att_end), and sets it against Phase 0's warm AF3 forward time for a fold in that
bucket on the same card (report/runs.tsv, arm ap_af3, compile subtracted; AlphaPulldown 2.9.0). It is an Amdahl estimate, not a
measurement: the end-to-end pilot measures it.
"""
import collections
import glob
import json
import os
import statistics
import sys

BENCH = os.environ.get("BENCH", "/scratch/dima/kernel_bench_phase0")
G = os.path.join(BENCH, "gate0")
BUCKETS = (256, 512, 768, 1024, 1280, 1536, 2048, 2560, 3072, 3584, 4096, 4608, 5120)
CALLS = {128: 48 * 11 + 4 * 11 + 4 * 5, 64: 2 * 4 * 11}
OPS = {"trimul": ("trimul_out", "trimul_in"), "attention": ("att_start", "att_end")}
CARD_ORDER = ["h100", "h100pcie", "h200", "a100", "a40", "l40s", "3090", "rtx6000_fallback", "rtx6000", "b4500"]


def load():
    rows = []
    for f in sorted(glob.glob(os.path.join(G, "runs", "*", "*", "cells.jsonl"))):
        card = f.split(os.sep)[-3]
        part = f.split(os.sep)[-2]
        for line in open(f):
            r = json.loads(line)
            r["card"], r["part"] = card, part
            rows.append(r)
    return rows


def bucket(t):
    return next((b for b in BUCKETS if b >= t), None)


def phase0_fwd():
    """card -> bucket -> median warm forward seconds of AlphaPulldown's AF3 (arm ap_af3)."""
    out = collections.defaultdict(lambda: collections.defaultdict(list))
    p = os.path.join(BENCH, "report", "runs.tsv")
    if not os.path.exists(p):
        return {}
    lines = open(p).read().splitlines()
    h = lines[0].split("\t")
    for ln in lines[1:]:
        r = dict(zip(h, ln.split("\t")))
        if r.get("arm") == "ap_af3" and r.get("suite") in ("speed", "af3reach") and r.get("status") == "ok" and r.get("fwd_s"):
            b = bucket(int(r["tokens"]))
            if b:
                out[r["gpu"]][b].append(float(r["fwd_s"]))
    return {c: {b: statistics.median(v) for b, v in d.items()} for c, d in out.items()}


def fmt(x, nd=2, dash="–"):
    return dash if x is None else f"{x:.{nd}f}"


def main():
    rows = load()
    if not rows:
        print("no Gate 0 results under", G)
        return 1
    cards = sorted({r["card"] for r in rows}, key=lambda c: (CARD_ORDER.index(c) if c in CARD_ORDER else 99, c))
    cell = {}                       # (card, variant, C, N, mask, weights, arm) -> record (latest wins)
    for r in rows:
        cell[(r["card"], r["variant"], r["C"], r["N"], r["mask"], r["weights"], r["arm"])] = r
    keys = ["card", "part", "device", "cc", "tiles", "jax", "variant", "C", "N", "n_real", "mask", "weights", "arm", "status", "ms", "ms_p10",
            "ms_p90", "loop_k", "compile_s", "temp_mb", "out_mb", "rel", "max", "vs_stock_rel", "gate", "leak_ok", "det_ok", "pad_finite",
            "real_finite", "served_reason", "error"]
    with open(os.path.join(G, "gate0_cells.tsv"), "w") as f:
        f.write("\t".join(keys) + "\n")
        for r in rows:
            f.write("\t".join("" if r.get(k) is None else str(r.get(k)).replace("\t", " ").replace("\n", " ")[:300] for k in keys) + "\n")

    md = ["# Gate 0: the kit's fused triangle kernels vs our AF3 fork, layer by layer", "",
          "Generated by `gate0/gate0_collect.py`; one row per (card, op, C, N). Speed-up = stock ms / arm ms, **> 1 = faster than our fork's module**.",
          "Arms: `fused` = the kit's Pallas prologue + core + epilogue; `tokcore` = the kit's prologue/epilogue around tokamax's flash core;",
          "`nochunk` = the stock module with row chunking off. Memory = XLA temp bytes of one layer call.", ""]

    # inventory
    md += ["## Runs", "", "| card | part | device | cc | tiles | jax | cells | statuses |", "|---|---|---|---|---|---|---|---|"]
    by_run = collections.defaultdict(list)
    for r in rows:
        by_run[(r["card"], r["part"])].append(r)
    for (card, part), rs in sorted(by_run.items(), key=lambda kv: (cards.index(kv[0][0]), kv[0][1])):
        st = collections.Counter(f"{r['arm']}:{r['status']}" for r in rs)
        n_cells = len({(r["variant"], r["C"], r["N"], r["mask"], r["weights"]) for r in rs})
        md.append(f"| {card} | {part} | {rs[0].get('device')} | {rs[0].get('cc')} | {rs[0].get('tiles')} | {rs[0].get('jax')} | {n_cells} | "
                  + ", ".join(f"{k} {v}" for k, v in sorted(st.items()) if not k.endswith(":ok")) + " |")
    md.append("")

    # correctness
    md += ["## Correctness (all masks and weights)", "",
           "Gate per cell: rel_fused ≤ 1.2·rel_stock + 1e-3 and max_fused ≤ 2·max_stock + 1e-2, both against the f64 reference on the real region.",
           "`biasT` is the negative control (OpenFold ending-node bias): it must fail.", "",
           "| card | arm | cells | gate pass | leak ok | deterministic | padded finite | real finite | worst rel / stock rel | worst max / stock max |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for card in cards:
        for arm in ("fused", "fused_tokcore", "fused_biasT", "stock", "stock_nochunk"):
            rs = [r for r in rows if r["card"] == card and r["arm"] == arm and r.get("status") == "ok"]
            if not rs:
                continue
            g = [r.get("gate") for r in rs if r.get("gate") is not None]
            ratios_rel, ratios_max = [], []
            for r in rs:
                s = cell.get((card, r["variant"], r["C"], r["N"], r["mask"], r["weights"], "stock"))
                if s and r.get("rel") and s.get("rel"):
                    ratios_rel.append(r["rel"] / s["rel"])
                    ratios_max.append(r["max"] / s["max"])
            cnt = lambda k: f"{sum(1 for r in rs if r.get(k) is True)}/{sum(1 for r in rs if r.get(k) is not None)}"   # noqa: E731
            md.append(f"| {card} | {arm} | {len(rs)} | {sum(g)}/{len(g) if g else 0} | {cnt('leak_ok')} | {cnt('det_ok')} | {cnt('pad_finite')} | "
                      f"{cnt('real_finite')} | {fmt(max(ratios_rel) if ratios_rel else None)} | {fmt(max(ratios_max) if ratios_max else None)} |")
    fails = [r for r in rows if r.get("gate") is False and r["arm"] != "fused_biasT"]
    if fails:
        md += ["", "Gate failures:", ""] + [f"- {r['card']} {r['variant']} C={r['C']} N={r['N']} {r['mask']} {r['weights']} {r['arm']}: "
                                             f"rel {fmt(r.get('rel'), 4)} max {fmt(r.get('max'), 3)}" for r in fails]
    md.append("")

    # speed and memory, random weights + padded mask
    md += ["## Speed-up and memory per layer (random weights, bucket-padded mask)", ""]
    for card in cards:
        md += [f"### {card}", "", "| op | C | N | stock ms | fused× | tokcore× | nochunk× | stock MB | fused MB | Δ MB |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for variant in ("trimul_out", "trimul_in", "att_start", "att_end"):
            for C in (128, 64):
                for N in BUCKETS:
                    s = cell.get((card, variant, C, N, "pad", "rand", "stock"))
                    if not s:
                        continue
                    a = {arm: cell.get((card, variant, C, N, "pad", "rand", arm)) for arm in ("fused", "fused_tokcore", "stock_nochunk")}
                    sp = lambda x: (s["ms"] / x["ms"]) if (x and x.get("ms") and s.get("ms")) else None   # noqa: E731
                    st = lambda x: (x or {}).get("status", "–") if not (x and x.get("ms")) else None    # noqa: E731
                    cellv = lambda x: fmt(sp(x)) if sp(x) is not None else (st(x) or "–")                # noqa: E731
                    f_ = a["fused"] or {}
                    dmem = (f_["temp_mb"] - s["temp_mb"]) if (f_.get("temp_mb") is not None and s.get("temp_mb") is not None) else None
                    md.append(f"| {variant} | {C} | {N} | {fmt(s.get('ms'), 3) if s.get('ms') else s.get('status')} | {cellv(a['fused'])} | "
                              f"{cellv(a['fused_tokcore'])} | {cellv(a['stock_nochunk'])} | {fmt(s.get('temp_mb'), 0)} | {fmt(f_.get('temp_mb'), 0)} | "
                              f"{fmt(dmem, 0)} |")
        md.append("")

    # projection
    fwd = phase0_fwd()
    md += ["## Projected saving per AF3 prediction (one seed)", "",
           f"Calls per prediction: {CALLS[128]} of each C=128 variant, {CALLS[64]} of each C=64 variant. Saving = Σ calls × (stock − fused) per layer.",
           "Phase 0 forward = AlphaPulldown 2.9.0's warm AF3 forward for a fold in that bucket on that card (compile subtracted).", "",
           "| card | N | trimul saving s | attention saving s (fused) | attention saving s (best arm) | Phase 0 forward s | projected speed-up |",
           "|---|---|---|---|---|---|---|"]
    for card in cards:
        base = card.replace("_fallback", "")
        for N in BUCKETS:
            sav = {"trimul": 0.0, "att_fused": 0.0, "att_best": 0.0}
            complete = True
            for op, variants in OPS.items():
                for v in variants:
                    for C in (128, 64):
                        s = cell.get((card, v, C, N, "pad", "rand", "stock"))
                        f_ = cell.get((card, v, C, N, "pad", "rand", "fused"))
                        if not (s and s.get("ms") and f_ and f_.get("ms")):
                            complete = False
                            continue
                        d = CALLS[C] * (s["ms"] - f_["ms"]) / 1e3
                        if op == "trimul":
                            sav["trimul"] += d
                        else:
                            sav["att_fused"] += d
                            alts = [x["ms"] for x in (f_, cell.get((card, v, C, N, "pad", "rand", "fused_tokcore")),
                                                      cell.get((card, v, C, N, "pad", "rand", "stock_nochunk"))) if x and x.get("ms")]
                            sav["att_best"] += CALLS[C] * (s["ms"] - min(alts)) / 1e3
            if not any(cell.get((card, v, C, N, "pad", "rand", "stock")) for v in OPS["trimul"] + OPS["attention"] for C in (128, 64)):
                continue
            t = fwd.get(base, {}).get(N)
            proj = t / (t - sav["trimul"] - sav["att_fused"]) if (t and complete and t > sav["trimul"] + sav["att_fused"]) else None
            md.append(f"| {card} | {N} | {fmt(sav['trimul'], 1)} | {fmt(sav['att_fused'], 1)} | {fmt(sav['att_best'], 1)} | {fmt(t, 1)} | "
                      f"{fmt(proj) + ('' if complete else ' (partial)') if proj else ('–' if complete else 'incomplete')} |")
    md.append("")
    out = os.path.join(G, "GATE0.md")
    open(out, "w").write("\n".join(md) + "\n")
    print("wrote", out, "and", os.path.join(G, "gate0_cells.tsv"), f"({len(rows)} records, cards: {' '.join(cards)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
